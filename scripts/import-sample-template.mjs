#!/usr/bin/env node
/**
 * Converts NMU's task spreadsheet (exported as CSV) into the app's sample template.
 *
 *   npm run sample:import [path/to/file.csv]
 *
 * Default input: data/sample-template-program-tasks.csv
 * Expected columns: Timeline, Task, Owner, Role (others are ignored).
 * Writes:
 *   src/lib/data/sample-template-tasks.ts       (used by the development placeholder)
 *   data/airtable-import/template-steps.csv      (ready to import into Airtable "Template Steps" later)
 * Fails loudly if a timeline label can't be understood, so no task is silently dropped.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { parseTimeline } from "../src/lib/domain/timeline.ts";

const input = process.argv[2] ?? new URL("../data/sample-template-program-tasks.csv", import.meta.url).pathname;
const rows = parseCsv(readFileSync(input, "utf8"));
const header = rows.shift().map((h) => h.trim().toLowerCase());
const col = (name) => {
  const i = header.indexOf(name);
  if (i < 0) throw new Error(`Missing column "${name}" in ${input}`);
  return i;
};
const [iTimeline, iTask, iOwner, iRole] = ["timeline", "task", "owner", "role"].map(col);
const list = (s) => (s ?? "").split(",").map((x) => x.trim()).filter(Boolean);

const tasks = [];
const errors = [];
rows.forEach((r, n) => {
  if (r.every((c) => !c.trim())) return;
  const timeline = r[iTimeline]?.trim() ?? "";
  const title = r[iTask]?.trim() ?? "";
  if (!title) return errors.push(`Row ${n + 2}: no task title`);
  const rule = parseTimeline(timeline);
  if (!rule) return errors.push(`Row ${n + 2}: can't understand timeline "${timeline}"`);
  const owners = list(r[iOwner]);
  const roles = list(r[iRole]);
  if (owners.length !== roles.length) errors.push(`Row ${n + 2}: ${owners.length} owner(s) but ${roles.length} role(s)`);
  tasks.push({ order: tasks.length + 1, timeline, title, roles, owners, ...rule });
});
if (errors.length) {
  console.error(`Could not import ${input}:\n  - ${errors.join("\n  - ")}`);
  process.exit(1);
}

// Default person for each role (first owner listed against it)
const roleOwners = {};
for (const t of tasks) t.roles.forEach((role, i) => {
  roleOwners[role] ??= t.owners[i];
});

const ts = `/**
 * GENERATED by scripts/import-sample-template.mjs from data/sample-template-program-tasks.csv.
 * Do not edit by hand; edit the CSV and run \`npm run sample:import\`.
 * Sample data for the development placeholder only.
 */
export interface SampleTemplateTask {
  order: number;
  /** Original spreadsheet label, e.g. "4 months prior" */
  timeline: string;
  title: string;
  roles: string[];
  owners: string[];
  offsetAmount: number;
  offsetUnit: "Days" | "Weeks" | "Months";
  timing: "Before" | "After";
  anchor: "Program Start" | "Program End";
  phase: "Pre-launch" | "During program" | "Post-program";
}

export const SAMPLE_TEMPLATE_TASKS: SampleTemplateTask[] = ${JSON.stringify(tasks, null, 2)};

/** Who usually fills each role, per the spreadsheet. */
export const SAMPLE_ROLE_OWNERS: Record<string, string> = ${JSON.stringify(roleOwners, null, 2)};
`;
writeFileSync(new URL("../src/lib/data/sample-template-tasks.ts", import.meta.url), ts);

const esc = (v) => (/[",\n]/.test(String(v)) ? `"${String(v).replace(/"/g, '""')}"` : String(v));
const csv = [
  ["Title", "Order", "Phase", "Offset Amount", "Offset Unit", "Timing", "Anchor", "Default Owner Role"],
  ...tasks.map((t) => [t.title, t.order, t.phase, t.offsetAmount, t.offsetUnit, t.timing, t.anchor, t.roles.join(", ")]),
]
  .map((r) => r.map(esc).join(","))
  .join("\n");
mkdirSync(new URL("../data/airtable-import/", import.meta.url), { recursive: true });
writeFileSync(new URL("../data/airtable-import/template-steps.csv", import.meta.url), csv + "\n");

console.log(`Imported ${tasks.length} tasks, ${Object.keys(roleOwners).length} roles:`);
for (const [role, owner] of Object.entries(roleOwners)) console.log(`  ${role}: ${owner}`);

/** Minimal RFC 4180 CSV parser (quoted fields, escaped quotes, newlines in quotes). */
function parseCsv(text) {
  const out = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      out.push(row);
      row = [];
      field = "";
    } else field += c;
  }
  if (field || row.length) {
    row.push(field);
    out.push(row);
  }
  return out;
}
