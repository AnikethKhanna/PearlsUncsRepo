#!/usr/bin/env node
/**
 * Inspect NMU's Airtable base and compare it with src/lib/airtable/schema.ts.
 *
 *   npm run airtable:inspect
 *
 * Needs AIRTABLE_TOKEN (with the schema.bases:read scope) and AIRTABLE_BASE_ID
 * in .env.local. READ-ONLY: it never changes the base. It writes
 * docs/airtable-schema.generated.md (table/field names and types only,
 * no record data) and prints any mismatches with the app's mapping.
 */
import { writeFileSync } from "node:fs";
import { AIRTABLE_SCHEMA } from "../src/lib/airtable/schema.ts";

const token = process.env.AIRTABLE_TOKEN;
const baseId = process.env.AIRTABLE_BASE_ID;
if (!token || !baseId) {
  console.error("Set AIRTABLE_TOKEN and AIRTABLE_BASE_ID in .env.local first (see .env.example).");
  process.exit(1);
}

// Field types the app expects (others are accepted with a warning).
const LINK = ["multipleRecordLinks"];
const TEXT = ["singleLineText", "multilineText", "richText", "email", "singleSelect", "formula", "multipleLookupValues", "rollup", "url"];
const EXPECTED = {
  users: { email: ["email", "singleLineText"], accessLevel: ["singleSelect", "singleLineText"], active: ["checkbox"], assignedTasks: LINK, projects: LINK },
  templates: { active: ["checkbox"], steps: LINK },
  steps: { template: LINK, order: ["number", "autoNumber"], offsetAmount: ["number"], offsetUnit: ["singleSelect", "singleLineText"], timing: ["singleSelect", "singleLineText"], anchor: ["singleSelect", "singleLineText"], defaultOwnerRoles: ["multipleSelects"], dependsOn: LINK, defaultAssignees: LINK },
  projects: { site: LINK, template: LINK, startDate: ["date"], endDate: ["date"], status: ["singleSelect"], team: LINK, tasks: LINK, createdBy: LINK },
  tasks: { project: LINK, templateStep: LINK, assignees: LINK, order: ["number"], dueDate: ["date"], status: ["singleSelect"], dependsOn: LINK, completedAt: ["date"], documentLinks: ["multilineText", "url", "singleLineText", "richText"] },
};

const res = await fetch(`https://api.airtable.com/v0/meta/bases/${encodeURIComponent(baseId)}/tables`, {
  headers: { Authorization: `Bearer ${token}` },
});
if (!res.ok) {
  console.error(`Airtable returned ${res.status}. Check the token has schema.bases:read and access to this base.`);
  process.exit(1);
}
const { tables } = await res.json();
const byName = new Map(tables.flatMap((t) => [[t.name, t], [t.id, t]]));
const tableName = (id) => tables.find((t) => t.id === id)?.name ?? id;

// ---- Document the real base ----
let md = `# Airtable base schema (generated)\n\nGenerated by \`npm run airtable:inspect\` on ${new Date().toISOString().slice(0, 10)}.\nNames and types only — no record data.\n`;
for (const t of tables) {
  md += `\n## ${t.name}\n\n| Field | Type | Details |\n| --- | --- | --- |\n`;
  for (const f of t.fields) {
    let details = "";
    if (f.type === "multipleRecordLinks") details = `→ ${tableName(f.options?.linkedTableId)}${f.options?.prefersSingleRecordLink ? " (single)" : ""}`;
    else if (f.type === "singleSelect" || f.type === "multipleSelects") details = (f.options?.choices ?? []).map((c) => c.name).join(", ");
    md += `| ${f.name}${f.id === t.primaryFieldId ? " (primary)" : ""} | ${f.type} | ${details} |\n`;
  }
}

// ---- Compare with the app's mapping ----
// Fields the app works without (features that need them say so).
const OPTIONAL = new Set(["steps.defaultAssignees"]);

const problems = [];
const warnings = [];
for (const [key, spec] of Object.entries(AIRTABLE_SCHEMA)) {
  const table = byName.get(spec.table);
  if (!table) {
    problems.push(`Missing table "${spec.table}" (schema.ts → ${key}.table)`);
    continue;
  }
  const fields = new Map(table.fields.flatMap((f) => [[f.name, f], [f.id, f]]));
  for (const [fkey, fname] of Object.entries(spec.fields)) {
    const f = fields.get(fname);
    if (!f) {
      const msg = `Missing field "${spec.table}" → "${fname}" (schema.ts → ${key}.fields.${fkey})`;
      if (OPTIONAL.has(`${key}.${fkey}`)) warnings.push(`${msg}: optional, needed only for "Save as Template" with "remember who was assigned"`);
      else problems.push(msg);
      continue;
    }
    const expected = EXPECTED[key]?.[fkey] ?? (fkey === "name" || fkey === "title" ? [...TEXT, "autoNumber"] : null);
    if (expected && !expected.includes(f.type))
      warnings.push(`"${spec.table}" → "${fname}" is ${f.type}; app expects ${expected.join(" or ")}`);
  }
}

md += `\n## Comparison with src/lib/airtable/schema.ts\n\n`;
md += problems.length ? problems.map((p) => `- ❌ ${p}`).join("\n") + "\n" : "- ✅ Every table and field the app uses exists.\n";
md += warnings.map((w) => `- ⚠️ ${w}`).join("\n") + (warnings.length ? "\n" : "");
writeFileSync(new URL("../docs/airtable-schema.generated.md", import.meta.url), md);

console.log(`Found ${tables.length} tables: ${tables.map((t) => t.name).join(", ")}`);
console.log("Wrote docs/airtable-schema.generated.md");
if (problems.length) console.log(`\n${problems.length} problem(s):\n  - ${problems.join("\n  - ")}`);
if (warnings.length) console.log(`\n${warnings.length} warning(s):\n  - ${warnings.join("\n  - ")}`);
if (!problems.length) console.log("\n✅ The app's mapping matches this base.");
process.exit(problems.length ? 2 : 0);
